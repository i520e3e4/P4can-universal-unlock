"""Local (compiler-free) regression checks for the burst-flash integration.

The C++ state machine is covered by tests/test_burst_flash_pure.cpp, which is
compiled and run on the build VM. This file covers the parts that can drift
silently on a workstation: generated assets, dictionary coverage, API route
parity, and the evidence-to-code constants.

Run:  python tests/test_burst_flash_host.py
"""
from __future__ import annotations

import gzip
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORKSPACE = ROOT.parent
FAILURES: list[str] = []


def check(ok: bool, what: str) -> None:
    if not ok:
        FAILURES.append(what)


def read(rel: str) -> str:
    return (ROOT / rel).read_text(encoding="utf-8")


def test_generated_asset() -> None:
    src = (ROOT / "dashboard_source.html").read_bytes()
    hdr = read("index_html.h")
    m = re.search(r"INDEX_HTML_GZ_LEN\s*=\s*(\d+)", hdr)
    check(m is not None, "index_html.h declares INDEX_HTML_GZ_LEN")
    if not m:
        return
    packed = gzip.compress(src, mtime=0)
    check(len(packed) == int(m.group(1)),
          f"gzip length matches header ({len(packed)} vs {m.group(1)})")
    check("INDEX_HTML_GZ" in hdr and "PROGMEM" in hdr,
          "index_html.h contains the PROGMEM gzip array")


def test_i18n() -> None:
    cfg = json.loads(read("tools/i18n_source.json"))
    strings = cfg["strings"]
    need = [
        "Burst Flash", "Master Enable", "Stationary Gate", "Bench Mode",
        "Vehicle state", "Physical input", "CAN ready", "Stock 0x249",
        "Learning", "Last reject", "Stop All", "Front Burst Flash",
        "Rear Burst Flash", "Channel Enable", "Count", "On ms", "Off ms",
        "Template", "Learn Values", "Trigger Once", "Not validated",
        "Learned in-car", "Manually confirmed",
    ]
    missing = [s for s in need if s not in strings]
    check(not missing, f"burst-flash UI strings translated (missing: {missing})")
    for en in need:
        zh = strings.get(en, "")
        check(bool(zh) and zh != en, f"translation differs from source: {en}")
    check("Sessions" in cfg["tokens"] and "TX OK" in cfg["tokens"],
          "status counters have state tokens")


def test_routes() -> None:
    runtime = read("burst_flash.h")
    html = read("dashboard_source.html")
    routes = set(re.findall(r'server\.on\("(/api/burst-flash/[^"]+)"', runtime))
    used = set(re.findall(r"(/api/burst-flash/[a-z-]+)", html))
    check(len(routes) == 8, f"8 API routes registered (found {len(routes)})")
    check(used <= routes, f"dashboard only calls registered routes (extra: {used - routes})")


def test_dom_ids() -> None:
    html = read("dashboard_source.html")
    ids = set(re.findall(r'id="(bf[A-Za-z0-9]+)"', html))
    for needed in ("bfMaster", "bfStationary", "bfBench", "bfVehicle",
                   "bfPhysical", "bfCan", "bfStock", "bfLearn",
                   "bfReject", "bfChannels", "bfStop"):
        check(needed in ids, f"static DOM id present: {needed}")
    # Channel controls are generated by JS; their id templates must exist.
    for tpl in ("bfEn", "bfCnt", "bfOn", "bfOff", "bfTpl", "bfLearn", "bfGo", "bfStat"):
        check(f"{tpl}'+i+'" in html or f'"{tpl}"' in html or f"${tpl}" in html
              or re.search(r"['\"]" + tpl + r"['\"]\s*\+", html) is not None,
              f"generated channel id template present: {tpl}")


def test_evidence_constants() -> None:
    pure = read("burst_flash_pure.h")
    expected = {
        "BURST_FLASH_FRONT_ID_PURE": "0x249",
        "BURST_FLASH_REAR_ID_PURE": "0x3F4",
        "BURST_FLASH_VCLEFT_STATUS_ID_PURE": "0x3E2",
        "BURST_FLASH_VCRIGHT_STATUS_ID_PURE": "0x3E3",
        "BURST_FLASH_UI_CTRL3_ID_PURE": "0x294",
        "BURST_FLASH_HIGHBEAM_MASK_PURE": "0x30",
        "BURST_FLASH_REAR_MASK_PURE": "0x0E",
        "BURST_FLASH_MUX_MASK_PURE": "0x1F",
    }
    for name, value in expected.items():
        m = re.search(name + r"\s*=\s*(0x[0-9A-Fa-f]+)", pure)
        check(m is not None and m.group(1).lower() == value.lower(),
              f"constant {name} == {value}")

    frames_path = WORKSPACE / "burst_flash_frames.json"
    if frames_path.exists():
        data = json.loads(frames_path.read_text(encoding="utf-8"))
        by_id = {f["id"]: f for f in data["frames"]}
        check(by_id["0x249"]["dlc_hint"] == 4, "DBC front frame DLC 4")
        check(by_id["0x3F4"]["cycle_ms"] == 0, "DBC rear frame is event-triggered")
        front_hb = next(s for s in by_id["0x249"]["signals"]
                        if s["name"] == "SCCM_highBeamStalkStatus")
        check(front_hb["start"] == 12 and front_hb["width"] == 2,
              "DBC high-beam signal is byte1 bit4-5")
        rear = next(s for s in by_id["0x3F4"]["signals"]
                    if s["name"] == "LS_lightBrakeRequest")
        check(rear["byte"] == 7 and rear["mask"] == "0x02",
              "DBC brake request is byte7 bit1")


def test_defaults_and_wiring() -> None:
    pure = read("burst_flash_pure.h")
    check("c.masterEnabled = false;" in pure, "master disabled by default")
    check("f.enabled = false; f.templateValid = false;" in pure,
          "front channel disabled/unvalidated by default")
    check("r.enabled = false; r.templateValid = false;" in pure,
          "rear channel disabled/unvalidated by default")

    runtime = read("burst_flash.h")
    call = "if (!stalkFrameSnapshot(counter, stock)) return false;"
    check(runtime.count(call) == 1,
          "stalkFrameSnapshot called exactly once (only at transmit time)")
    # Guard against a future refactor reintroducing polling from the tick.
    code_lines = [l for l in runtime.splitlines()
                  if not l.lstrip().startswith(("//", "*", "/*"))]
    check("\n".join(code_lines).count("stalkFrameSnapshot(") == 1,
          "no other stalkFrameSnapshot call outside the transmit function")
    check("leftStalkChecksumPure" in read("auto_blinker_pure.h"),
          "existing stalk CRC helper still present")

    ino = read("P4-CAN-Universal-v3.29.3.ino")
    check("burstFlashInit();" in ino, "runtime init wired into setup()")
    check(ino.index('#include "vehicle_logic.h"') < ino.index('#include "burst_flash.h"')
          < ino.index('#include "web_api.h"'),
          "include order keeps static helpers visible")
    rt = read("can_runtime.h")
    check(rt.count("burstFlashObserveRx(") == 2,
          "both CAN RX paths feed the observer")
    check("burstFlashTick(captureNow);" in rt, "service tick wired")
    check("burstFlashRegisterRoutes();" in read("web_api.h"),
          "web routes registered")


def main() -> int:
    test_generated_asset()
    test_i18n()
    test_routes()
    test_dom_ids()
    test_evidence_constants()
    test_defaults_and_wiring()
    if FAILURES:
        print(f"FAIL: {len(FAILURES)} problem(s)")
        for f in FAILURES:
            print("  -", f)
        return 1
    print("PASS: burst-flash integration (assets, i18n, routes, DOM, "
          "evidence constants, defaults, wiring)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
